#!/usr/bin/env python3
"""Generate the category-exclusion list for the SIX NEW SAST packs (D-104, M8.15 S2).

Reads every loaded rule (*.yaml/*.yml, excluding *.test.yaml/*.test.yml) under the six NEW packs
(python/go/php/ruby/kotlin/scala) of a baked opengrep-rules root, and emits the FULL check_ids
(opengrep-rules.<dotted-rel-dir>.<id>) of rules whose metadata.category is one of the excluded
categories. The existing four packs (java/csharp/javascript/typescript) are NEVER touched — removing
an existing rule would make reconcile "solve" its live findings (reads as fixed), a separate decision.

check_id derivation matches the loader: filename is NOT part of the id; a file may hold several rules,
each with its own metadata.category, so exclusion is per-rule, not per-file.

Default output is the exact committed file body (stable header + sorted check_ids), regenerated and
diffed by :app:opengrepExclusionsInImageTest — a diff fails the build so category changes get reviewed.
`--report` prints JSON: per-pack excluded counts, the kept security count, and the "other/missing"
rules (category value is neither security nor an excluded category, or is absent) for the S2 report.

Run inside the image:  python3 -I gen_category_exclusions.py /etc/secscan/opengrep-rules [--report]
Stdlib + PyYAML (shipped in the image).
"""
import os
import sys
import json

import yaml

NEW_PACKS = ("python", "go", "php", "ruby", "kotlin", "scala")
# sorted, D-104. "compatibility" added (M8.15 follow-up): python36/37 + django-compat rules flag
# version-portability, not security risk in a scanned repo. flask-cache-query-string stays (category
# "caching", kept).
EXCLUDED = ("best-practice", "compatibility", "correctness", "maintainability", "performance")
HEADER = (
    "# GENERATED by scanner-image/gen_category_exclusions.py — DO NOT EDIT BY HAND.\n"
    "# Full check_ids of rules in the SIX NEW packs (python/go/php/ruby/kotlin/scala) whose\n"
    "# metadata.category is one of: best-practice, compatibility, correctness, maintainability,\n"
    "# performance (D-104, M8.15). The existing four packs are never excluded. Regenerated + diffed\n"
    "# against this file by :app:opengrepExclusionsInImageTest; any diff fails the build so category\n"
    "# changes are reviewed.\n"
    "# Applied at scan time via opengrep --exclude-rule (+ results[] post-filter fallback), like the deny-list.\n"
)


def iter_rules(root):
    """Yield (full_check_id, category_or_None) for every loaded rule in the six new packs."""
    for pack in NEW_PACKS:
        base = os.path.join(root, pack)
        for dp, _, fns in os.walk(base):
            for fn in fns:
                low = fn.lower()
                if not (low.endswith(".yaml") or low.endswith(".yml")):
                    continue
                if low.endswith(".test.yaml") or low.endswith(".test.yml"):
                    continue
                p = os.path.join(dp, fn)
                reldir = os.path.relpath(dp, root).replace(os.sep, ".")
                try:
                    with open(p, encoding="utf-8") as fh:
                        doc = yaml.safe_load(fh)
                except Exception as e:  # noqa: BLE001 — a malformed rule file must not silently drop rules
                    sys.stderr.write(f"ERROR parsing {p}: {e}\n")
                    sys.exit(2)
                if not isinstance(doc, dict):
                    continue
                for rule in doc.get("rules", []) or []:
                    if not isinstance(rule, dict) or "id" not in rule:
                        continue
                    meta = rule.get("metadata") or {}
                    cat = meta.get("category") if isinstance(meta, dict) else None
                    yield ("opengrep-rules." + reldir + "." + str(rule["id"]), cat)


def main():
    root = os.path.abspath(sys.argv[1])
    report = "--report" in sys.argv[2:]
    excluded = set()
    other = {}          # check_id -> category value (None/other)
    security = 0
    per_pack = {p: 0 for p in NEW_PACKS}
    for cid, cat in iter_rules(root):
        if cat in EXCLUDED:
            excluded.add(cid)
            per_pack[cid.split(".")[1]] += 1
        elif cat == "security":
            security += 1
        else:
            other[cid] = cat  # missing (None) or some other value
    if report:
        print(json.dumps({
            "root": root,
            "excluded_total": len(excluded),
            "excluded_per_pack": per_pack,
            "security_kept": security,
            "other_or_missing_count": len(other),
            "other_or_missing": [{"check_id": c, "category": other[c]} for c in sorted(other)],
        }, indent=2))
        return
    sys.stdout.write(HEADER)
    for cid in sorted(excluded):
        sys.stdout.write(cid + "\n")


if __name__ == "__main__":
    main()
